-- 079_telegram_dictionary.sql
--
-- Правки словарей ЖКХ-классификатора из интерфейса (§24: пороги и
-- словари подкручиваются по статистике, а гонять деплой ради пяти слов
-- бессмысленно).
--
-- ── Дельта, а не полная копия ────────────────────────────────────────
-- 413 встроенных корней ОСТАЮТСЯ в коде (utils/zhkh-classifier.ts).
-- Здесь хранятся только отклонения от них: добавленные термины и
-- отключённые встроенные.
--
-- Так сделано намеренно. Перенеси мы словарь целиком в БД —
-- пустая или недоступная таблица означала бы классификатор, который
-- молчит на всё, и это выяснилось бы не сразу: диспетчер и в норме
-- отвечает далеко не на каждое сообщение. При дельте пустая таблица
-- значит «как в коде», то есть рабочее состояние по умолчанию.
--
-- Побочная выгода: таблица остаётся маленькой и обозримой — по ней
-- видно, что именно УК меняла руками, а не 400 строк вперемешку.
--
-- ── Колонки ──────────────────────────────────────────────────────────
-- kind      'topic' | 'symptom' | 'negative' — в какой из трёх словарей.
-- category  Только для kind='topic': leak, sewage, electricity,
--           elevator, heating, garbage, lighting, common_property.
--           Для остальных NULL.
-- term      Корень слова в том виде, в каком его вводит человек.
--           Нормализацию (регистр, ё→е, апострофы, удвоения, пробелы)
--           делает классификатор при загрузке — хранить нормализованное
--           нельзя, иначе в интерфейсе появятся нечитаемые «неработа»
--           вместо «не работает».
-- lang      'ru' | 'uz' — только для группировки в интерфейсе. На
--           сопоставление не влияет: сравнение идёт по подстроке, языка
--           не знает.
-- action    'add' — добавить термин, которого нет в коде.
--           'disable' — выключить встроенный. Правка существующего =
--           disable старого плюс add нового; отдельного 'edit' нет,
--           потому что встроенные строки менять негде — они в файле.
--
-- ── Отклонение от §3 ─────────────────────────────────────────────────
-- Колонки tenant_id нет. Бот один на все УК, и классификатор у него
-- общий: словарь на тенанта раздробил бы качество распознавания и
-- потребовал бы отдельной выверки для каждого. Поэтому правки глобальны
-- и доступны только суперадмину — та же логика, что у telegram_updates.

CREATE TABLE IF NOT EXISTS telegram_dictionary (
  id TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  category TEXT,
  term TEXT NOT NULL,
  lang TEXT NOT NULL DEFAULT 'ru',
  action TEXT NOT NULL DEFAULT 'add',
  created_by TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Один и тот же термин не должен встречаться дважды в одном словаре:
-- иначе неясно, какая из двух строк «главная», а отключение одной не
-- даст эффекта из-за второй.
CREATE UNIQUE INDEX IF NOT EXISTS idx_telegram_dictionary_unique
  ON telegram_dictionary(kind, COALESCE(category, ''), term, action);

CREATE INDEX IF NOT EXISTS idx_telegram_dictionary_kind
  ON telegram_dictionary(kind);
