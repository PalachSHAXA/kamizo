-- 073_telegram_updates.sql
--
-- Дедупликация входящих Telegram-апдейтов (§20 ТЗ: «не обрабатывать
-- один update дважды»).
--
-- Зачем: Telegram считает апдейт доставленным только после HTTP 200.
-- Если наш ответ задержался, потерялся в сети или сервис перезапустили
-- между обработкой и ответом — тот же update_id прилетит снова. Для
-- /start с токеном это закрыто одноразовостью токена, но для команд с
-- побочными эффектами (подключение группы, callback «Оформить заявку»,
-- будущее подтверждение входа) повтор означает второе выполнение.
--
-- Механика: update_id — PRIMARY KEY. Обработчик пробует INSERT первым
-- делом; конфликт означает «этот апдейт уже брали в работу» и мы сразу
-- отвечаем 200, ничего не делая. Это атомарно на уровне БД, поэтому
-- работает и при двух одновременных доставках одного апдейта.
--
-- ── Отклонение от §3 ─────────────────────────────────────────────────
-- У таблицы НЕТ колонки tenant_id, хотя ТЗ требует её у каждой новой
-- таблицы. Это осознанно: дедупликация происходит ДО того, как мы
-- вообще узнали, к какому тенанту относится апдейт — в этом её смысл.
-- Приписать сюда tenant_id можно было бы только после разбора апдейта,
-- то есть после того, как побочный эффект уже случился. Таблица не
-- содержит данных тенантов: только числовой счётчик Telegram и
-- отметку времени, поэтому и изолировать здесь нечего.
--
-- ── Рост таблицы ─────────────────────────────────────────────────────
-- Строка на каждый входящий апдейт. Без уборки таблица растёт вечно.
-- Чистка — при вставке, дешёвым DELETE по индексу received_at (см.
-- routes/telegram/webhook.ts). Горизонт 7 суток: Telegram прекращает
-- ретраи многократно раньше, так что более старая запись уже не может
-- защитить ни от чего.

CREATE TABLE IF NOT EXISTS telegram_updates (
  update_id TEXT PRIMARY KEY,
  received_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_telegram_updates_received
  ON telegram_updates(received_at);
