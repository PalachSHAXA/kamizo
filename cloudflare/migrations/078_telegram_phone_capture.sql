-- 078_telegram_phone_capture.sql
--
-- Сбор номера телефона через кнопку «Поделиться контактом» в боте.
--
-- ── Зачем ────────────────────────────────────────────────────────────
-- Сверка с продом (2026-08-27): из ~3040 активных жителей телефон
-- заполнен примерно у 30. У основной УК — 11 из 2347. То есть поле
-- users.phone фактически пустое, оно необязательно на всех уровнях
-- (схема, валидация регистрации, INSERT в auth.ts).
--
-- Это ломает выдачу кода подтверждения: otp.ts отказывает при пустом
-- телефоне. Но собрать номера «попросив жителей заполнить профиль» —
-- заведомо провальный путь.
--
-- Telegram отдаёт номер по кнопке request_contact, причём номер
-- ПОДТВЕРЖДЁН: это тот, на который зарегистрирован аккаунт. Качество
-- данных выше, чем у введённого руками.
--
-- ── Зачем отдельная таблица, а не колонка ────────────────────────────
-- Между «поделился контактом» и «подтвердил запись в профиль» нужно
-- где-то держать номер. Класть его в callback_data кнопки нельзя:
-- callback_data формирует КЛИЕНТ, и модифицированный клиент пришлёт
-- любой номер, какой захочет. В кнопку уходит только непрозрачный
-- идентификатор строки отсюда, а сам номер читается сервером из БД.
--
-- ── Колонки ──────────────────────────────────────────────────────────
-- telegram_user_id  Кто поделился. При подтверждении сверяется с тем,
--                   кто нажал кнопку: подтвердить чужую заявку нельзя.
-- phone             Уже нормализованный E.164 (+998...). Telegram
--                   отдаёт формат по-разному, с плюсом и без.
-- expires_at        ISO-строка; сверка в JS, не в SQL — причина та же,
--                   что в 070/071/076 ('T' против пробела при побайтовом
--                   сравнении).
-- used_at           Одноразовость. Повторное нажатие ничего не меняет.
--
-- ── Отклонение от §3 ─────────────────────────────────────────────────
-- Колонки tenant_id нет. Строка живёт секунды между двумя нажатиями и
-- принадлежит Telegram-аккаунту, а не тенанту: по §16 один Telegram
-- может быть привязан к аккаунтам в нескольких УК сразу, и номер
-- записывается во все. Приписать её одному тенанту было бы неверно.

CREATE TABLE IF NOT EXISTS telegram_pending_phones (
  id TEXT PRIMARY KEY,
  telegram_user_id TEXT NOT NULL,
  phone TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  expires_at TEXT NOT NULL,
  used_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_telegram_pending_phones_user
  ON telegram_pending_phones(telegram_user_id, used_at);
