-- 076_telegram_login_requests.sql
--
-- Этап 4 ТЗ (§17): подтверждение входа в Kamizo через Telegram.
--
-- Пароль проверен, но JWT ещё не выдан: пользователю в Telegram уходит
-- сообщение «Новый вход» с кнопками «Это я» / «Запретить вход», и токен
-- появляется только после нажатия первой.
--
-- ── Чего здесь СОЗНАТЕЛЬНО нет: самого JWT ───────────────────────────
-- Соблазн — выписать токен сразу и положить в строку до подтверждения.
-- Так делать нельзя: строка живёт в БД, попадает в бэкапы и в дампы, а
-- готовый JWT — это уже доступ. Токен выпускается в момент опроса
-- статуса, когда status='approved', и нигде не хранится.
--
-- ── Колонки ──────────────────────────────────────────────────────────
-- user_id / tenant_id  Определяются ИСКЛЮЧИТЕЛЬНО из проверенного
--                      логина. §17 прямо требует: «Tenant должен
--                      определяться из login-сессии и аккаунта
--                      пользователя, а не из Telegram callback».
--                      Callback приносит только id запроса и id
--                      нажавшего — оба перепроверяются по этой строке.
-- telegram_chat_id     Куда ушёл запрос. Дублирует telegram_users, и
--                      намеренно: привязку могут отозвать между
--                      отправкой и нажатием, а разбирать инцидент
--                      «кто подтвердил вход» надо по факту на тот
--                      момент.
-- telegram_message_id  Чтобы отредактировать сообщение после решения:
--                      кнопки должны исчезнуть, иначе человек жмёт их
--                      повторно и не понимает, почему ничего не
--                      происходит.
-- status               'pending' | 'approved' | 'denied' | 'expired'.
--                      Переход возможен только из 'pending' — это и
--                      есть одноразовость из §17. Повторное нажатие
--                      уже не меняет ничего.
-- device / ip_address  Показываются в сообщении, чтобы человек мог
--                      отличить свой вход от чужого. IP хранится ради
--                      разбора инцидентов; геолокацию не вычисляем —
--                      внешний сервис ради строки в сообщении не нужен,
--                      а §17 «Местоположение» оставляет на усмотрение.
-- resolved_at          Момент решения. Нужен аудиту (§22).
--
-- ── Срок жизни ───────────────────────────────────────────────────────
-- §17 задаёт около двух минут. Короткий срок здесь — не про удобство:
-- пока запрос в 'pending', любой, кто знает пароль, ждёт, что владелец
-- по невнимательности нажмёт «Это я». Чем уже окно, тем меньше шанс.
-- Значение задаётся в коде (routes/telegram/login-approval.ts), в
-- колонке лежит уже вычисленный момент в ISO-формате.
--
-- Сравнение срока — в JS через new Date(), НЕ в SQL. Причина та же, что
-- в 070/071: expires_at пишется как toISOString() ("...T...Z"), а
-- datetime('now') отдаёт "YYYY-MM-DD HH:MM:SS", и побайтовое сравнение
-- строк упирается в 'T' (0x54) против пробела (0x20) — 'T' больше
-- всегда, поэтому запись «истекала» бы только в полночь UTC.

CREATE TABLE IF NOT EXISTS telegram_login_requests (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL,
  user_id TEXT NOT NULL,
  telegram_chat_id TEXT NOT NULL,
  telegram_message_id TEXT,
  device TEXT,
  ip_address TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  expires_at TEXT NOT NULL,
  resolved_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_telegram_login_user
  ON telegram_login_requests(user_id, status);

CREATE INDEX IF NOT EXISTS idx_telegram_login_created
  ON telegram_login_requests(created_at);
