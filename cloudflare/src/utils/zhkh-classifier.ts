// Классификатор сообщений о проблемах ЖКХ (§11 ТЗ).
//
// Локальные правила, без внешних сервисов. §15 прямо требует: «В первой
// версии желательно использовать локальные правила или внутренний
// классификатор. Отправка домовых переписок во внешнюю LLM не должна
// включаться автоматически». Здесь ничего никуда не уходит — разбор
// целиком в процессе, текст не покидает VPS.
//
// ── Почему не по ключевым словам ─────────────────────────────────────
// §11 приводит пример, который ломает наивный подход:
//
//     «Кто знает, где купить хороший кран?»   — не проблема
//     «В третьем подъезде на первом этаже течёт кран.» — проблема
//
// Слово «кран» есть в обоих. Отличает их не тема, а НАМЕРЕНИЕ: во
// втором есть глагол-симптом («течёт»), в первом — маркер вопроса-
// просьбы («кто знает», «где купить»).
//
// Отсюда правило: сработка требует И темы, И симптома, И отсутствия
// маркеров, которые превращают фразу в вопрос, объявление или шутку.
//
// ── Языки и опечатки ─────────────────────────────────────────────────
// Домовые чаты в Узбекистане двуязычны и пишутся на бегу. Поэтому:
//
//   • узбекский латиницей — основной письменный вариант;
//   • узбекский кириллицей — всё ещё в ходу у старшего поколения;
//   • русский с типичными ошибками («тичет», «атопление», «прарвало»);
//   • слитное написание («неработает») и удвоения («теччёт»).
//
// Всё это решается не раздуванием словарей, а нормализацией: и текст,
// и словарные корни прогоняются через одну и ту же normalize(). После
// неё «не работает», «неработает» и «не  работает» — одна строка, а
// «oʻchdi», «o'chdi» и «ochdi» совпадают между собой.

export type ZhkhCategory =
  | 'leak' | 'sewage' | 'electricity' | 'elevator'
  | 'heating' | 'garbage' | 'lighting' | 'common_property';

export interface Classification {
  category: ZhkhCategory;
  confidence: number;
}

// ── Нормализация ─────────────────────────────────────────────────────
//
// Четыре шага, каждый закрывает свой класс расхождений:
//
//   1. Регистр и ё→е.
//   2. Апострофы. Узбекская латиница использует oʻ и gʻ, но набирают их
//      как o', o`, o’ или вовсе без знака. Убираем все варианты, тогда
//      «yoʻq», «yo'q» и «yoq» сходятся.
//   3. Удвоения букв схлопываются: «теччёт» → «течет», «issiq» →
//      «isiq». Словарь проходит ту же обработку, поэтому настоящие
//      удвоения (uzb. «ss», рус. «нн») не мешают — они схлопываются с
//      обеих сторон.
//   4. Пробелы удаляются целиком. Это уравнивает «не работает» и
//      «неработает» — самую частую слитную ошибку, — а заодно снимает
//      двойные пробелы и переносы строк.
//
// Пункт 4 теоретически может склеить слова в ложное совпадение, но
// корни здесь длинные и специфичные, а порог всё равно требует ещё и
// тему, и отсутствие стоп-маркеров.
function normalize(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[ʻʼ‘’'`´]/g, '')
    .replace(/(.)\1+/g, '$1')
    .replace(/\s+/g, '');
}

