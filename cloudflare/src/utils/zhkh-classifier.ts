// Верхняя граница длины. Простыни на тысячу символов — это обсуждение,
// объявление или пересланная статья, а не «у меня течёт». Разбирать их
// правилами бессмысленно, а ложные сработки они дают охотно.
//
// Считается по ИСХОДНОМУ тексту: normalize() убирает пробелы и заметно
// укорачивает строку, так что мерить после неё — мерить не то.
const MAX_LENGTH = 400;

export function classifyZhkhMessage(raw: string): Classification | null {
  if (!raw || raw.length > MAX_LENGTH) return null;
  const text = normalize(raw);
  if (!text) return null;

  // Отрицательные маркеры проверяем первыми: если человек спрашивает,
  // где купить кран, дальше считать нечего.
  if (NEGATIVE.some(n => text.includes(n))) return null;

  // Вопрос без симптома — это вопрос. «Когда включат отопление?»
  // содержит тему, но не поломку; предлагать по нему заявку неуместно.
  const symptoms = SYMPTOMS.filter(s => text.includes(s)).length;
  if (symptoms === 0) return null;

  // Выбираем тему с наибольшим числом совпадений. Сообщение «в подъезде
  // течёт труба» задевает и leak, и common_property — берём то, где
  // попаданий больше, при равенстве побеждает первый по порядку
  // объявления (leak приоритетнее, он же и опаснее).
  let best: { category: ZhkhCategory; hits: number } | null = null;
  for (const [category, words] of Object.entries(TOPICS) as [ZhkhCategory, string[]][]) {
    const hits = words.filter(w => text.includes(w)).length;
    if (hits > 0 && (!best || hits > best.hits)) best = { category, hits };
  }
  if (!best) return null;

  // Уверенность. Формула намеренно грубая: точность здесь иллюзорна,
  // а порог всё равно подбирается по статистике из
  // telegram_suggestions.outcome. Важно лишь, чтобы больше совпадений
  // давало больше уверенности и чтобы шкала не выходила за единицу.
  const confidence = Math.min(1, 0.45 + best.hits * 0.15 + Math.min(symptoms, 3) * 0.1);

  return { category: best.category, confidence };
}

// Порог сработки. §14 требует «использовать порог уверенности».
// 0.7 означает: нужна либо пара попаданий по теме, либо тема плюс
// несколько симптомов. Лучше промолчать, чем раздражать чат ложным
// предложением — жители отключат бота после второго такого.
export const SUGGESTION_THRESHOLD = 0.7;

