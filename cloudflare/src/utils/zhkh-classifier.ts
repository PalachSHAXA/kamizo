// ── Нормализация ─────────────────────────────────────────────────────
//
// Четыре шага, каждый закрывает свой класс расхождений:
//
//   1. Регистр и ё→е.
//   2. Апострофы. Узбекская латиница использует oʻ и gʻ, но набирают их
//      как o', o`, o’ или вовсе без знака. Убираем все варианты, тогда
//      «yoʻq», «yo'q» и «yoq» сходятся.
//   3. Удвоения букв схлопываются: «теччёт» → «течет», «issiq» →
//      «isiq». Словарь проходит ту же обработку, поэтому настоящие
//      удвоения (uzb. «ss», рус. «нн») не мешают — они схлопываются с
//      обеих сторон.
//   4. Пробелы удаляются целиком. Это уравнивает «не работает» и
//      «неработает» — самую частую слитную ошибку, — а заодно снимает
//      двойные пробелы и переносы строк.
//
// Пункт 4 теоретически может склеить слова в ложное совпадение, но
// корни здесь длинные и специфичные, а порог всё равно требует ещё и
// тему, и отсутствие стоп-маркеров.
function normalize(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[ʻʼ‘’'`´]/g, '')
    .replace(/(.)\1+/g, '$1')
    .replace(/\s+/g, '');
}

// То же самое, но границы слов сохранены. Знак препинания тоже считается
// границей: «подъезде,течет» — два слова, а не одно.
function normalizeSpaced(raw: string): string {
  const inner = raw
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[ʻʼ‘’'`´]/g, '')
    .replace(/(.)\1+/g, '$1')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
  return ' ' + inner + ' ';
}

// Порог, ниже которого корень ищется только с начала слова.
//
// normalize() удаляет пробелы, и без этого не ловились бы ни «лифт
// неработает», ни узбекская агглютинация. Но у склейки есть цена:
// короткий корень начинает совпадать в СЕРЕДИНЕ чужого слова. Так
// 'вода' находилась в «проВОДА», 'вон' — в «позВОНите», 'ток' — в
// «молоТОК», 'бак' — в «таБАК», 'зали' — в «покаЗАЛИ». Раньше это
// лечили поштучно, выкидывая корень за корнем ('том', 'бор', 'урна'),
// но так лечится симптом, а не причина: следующий короткий корень
// приносит ту же ошибку снова.
//
// Агглютинация не страдает: в узбекском корень стоит в начале слова
// («suvni», «liftda»), а окончания вроде 'yapti' и 'moqda' длиннее
// порога и ищутся по-прежнему по склейке.
//
// Цена решения: короткий корень перестаёт находиться, если пропущен
// пробел прямо перед ним («нетгорячейводы»). Это заметно реже, чем
// ложные срабатывания, которые правило убирает.
const WORD_START_MAX = 4;

function hasTerm(glued: string, spaced: string, term: string): boolean {
  return term.length > WORD_START_MAX
    ? glued.includes(term)
    : spaced.includes(' ' + term);
}

const N = (list: string[]) => list.map(normalize);

// ── Определение языка ────────────────────────────────────────────────
//
// Нужно, чтобы бот отвечал на языке сообщения. В группе он не знает, кто
// написал, пока человек не привязал аккаунт, поэтому users.language тут
// недоступен — язык приходится читать из самого текста.
//
// Три признака по убыванию надёжности:
//
//   1. Узбекские буквы кириллицы — ў, қ, ғ, ҳ. В русском их нет вовсе,
//      это стопроцентный признак.
//   2. Преобладание латиницы. В домовых чатах Узбекистана латиница —
//      это узбекский; русский пишут кириллицей. Транслит по-русски
//      («techet truba») теоретически возможен и будет определён как
//      узбекский, но это редкость, а цена ошибки — один ответ не на том
//      языке.
//   3. Служебные узбекские слова. Ловят смешанные фразы вроде
//      «в подъезде suv yoq», где скриптов поровну.
//
// Порядок важен: сначала однозначное, потом статистика, потом лексика.
const UZ_MARKERS = N([
  'yoq', 'yok', 'bor', 'qoldi', 'koldi', 'ketdi', 'emas', 'uchun',
  'bilan', 'yana', 'juda', 'iltimos', 'xona', 'uyda', 'yordam', 'kerak',
  'boldi', 'qilib', 'qiling', 'nima', 'qachon', 'kachon', 'menda',
  'bizda', 'edi', 'yapti', 'moqda', 'bor',
  // «бор» вернулось вместе с 'том': «заБОР» и «выБОР» его больше не
  // содержат, поиск идёт с начала слова.
  'йўқ', 'қолди', 'кетди', 'эмас', 'учун', 'билан', 'керак',
  'илтимос', 'ёрдам', 'қачон',
  // Узбекская кириллица не всегда содержит ў/қ/ғ/ҳ: «Лифт ишламайди,
  // туртинчи кун» — сплошь общие с русским буквы, и без этих маркеров
  // сообщение уходило как русское, а житель получал ответ не на своём
  // языке. Корни выбраны так, чтобы не сидеть внутри русских слов:
  // «кун» (день) сюда добавить нельзя — оно внутри «секунда», «окунь».
  'ишлам', 'ишлай', 'бузил', 'бузук', 'тушм', 'йиғил', 'йигил',
]);

export function detectLanguage(raw: string): ZhkhLang {
  const text = normalize(raw);
  const spaced = normalizeSpaced(raw);
  if (/[ўқғҳ]/.test(text)) return 'uz';

  const cyrillic = (text.match(/[а-я]/g) || []).length;
  const latin = (text.match(/[a-z]/g) || []).length;
  if (latin > cyrillic) return 'uz';

  if (UZ_MARKERS.some(m => hasTerm(text, spaced, m))) return 'uz';
  return 'ru';
}

