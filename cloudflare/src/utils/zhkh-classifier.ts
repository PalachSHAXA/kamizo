// Классификатор сообщений о проблемах ЖКХ (§11 ТЗ).
//
// Локальные правила, без внешних сервисов. §15 прямо требует: «В первой
// версии желательно использовать локальные правила или внутренний
// классификатор. Отправка домовых переписок во внешнюю LLM не должна
// включаться автоматически». Здесь ничего никуда не уходит — разбор
// целиком в процессе, текст не покидает VPS.
//
// ── Почему не по ключевым словам ─────────────────────────────────────
// §11 приводит пример, который ломает наивный подход:
//
//     «Кто знает, где купить хороший кран?»   — не проблема
//     «В третьем подъезде на первом этаже течёт кран.» — проблема
//
// Слово «кран» есть в обоих. Отличает их не тема, а НАМЕРЕНИЕ: во
// втором есть глагол-симптом («течёт»), в первом — маркер вопроса-
// просьбы («кто знает», «где купить»).
//
// Отсюда правило: сработка требует И темы, И симптома, И отсутствия
// маркеров, которые превращают фразу в вопрос, объявление или шутку.

export type ZhkhCategory =
  | 'leak' | 'sewage' | 'electricity' | 'elevator'
  | 'heating' | 'garbage' | 'lighting' | 'common_property';

export interface Classification {
  category: ZhkhCategory;
  confidence: number;
}

// Темы. Ключи намеренно в нижнем регистре и без окончаний — сравнение
// идёт по вхождению подстроки, чтобы «протечка/протекает/протечки»
// ловились одним корнем.
const TOPICS: Record<ZhkhCategory, string[]> = {
  leak: ['теч', 'протеч', 'потоп', 'залив', 'зали', 'кран', 'труб', 'вода', 'сантех', 'смесител', 'стояк'],
  sewage: ['канализ', 'засор', 'слив', 'унитаз', 'воняет', 'запах', 'фекал'],
  electricity: ['электр', 'свет', 'розетк', 'провод', 'щиток', 'пробк', 'напряжен', 'коротк'],
  elevator: ['лифт', 'подъемник', 'подъёмник'],
  heating: ['отоплен', 'батаре', 'радиатор', 'холодно', 'котел', 'котёл', 'горячая вода'],
  garbage: ['мусор', 'помойк', 'контейнер', 'бак', 'урна', 'свалк'],
  lighting: ['лампоч', 'фонар', 'освещен', 'темно', 'светильник'],
  common_property: ['дверь', 'домофон', 'подъезд', 'окно', 'перил', 'ступен', 'крыш', 'фасад', 'козырёк', 'козырек'],
};

// Симптомы — то, что превращает тему в сообщение о поломке.
const SYMPTOMS = [
  'теч', 'протек', 'капа', 'подтек', 'потоп', 'зали', 'прорв',
  'не работа', 'не рабоч', 'сломал', 'сломан', 'разбил', 'разбит',
  'не горит', 'нет свет', 'нет воды', 'нет отоплен', 'нет тепла',
  'застря', 'заклин', 'засор', 'воня', 'смерд', 'гуд', 'треск',
  'упал', 'обвал', 'трещин', 'потек', 'отвалил', 'висит',
  'холодн', 'ледян', 'не закрыва', 'не открыва', 'не убира',
  'переполн', 'завал', 'мига',
];

// Маркеры, снимающие сработку. Каждый — про то, что человек НЕ сообщает
// о поломке, а спрашивает, продаёт или шутит.
const NEGATIVE = [
  'кто знает', 'где купить', 'посоветуй', 'подскажите где', 'porekomend',
  'продам', 'продаю', 'куплю', 'сдам', 'сдаю', 'аренд',
  'спасибо', 'благодар', 'молодц', 'отлично сработал',
  'а если', 'а что если', 'интересно', 'шучу', 'шутка',
  'когда почин', 'уже почин', 'починили', 'исправил', 'всё работает',
  'вопрос:', 'подскажите пожалуйста где',
];

// Верхняя граница длины. Простыни на тысячу символов — это обсуждение,
// объявление или пересланная статья, а не «у меня течёт». Разбирать их
// правилами бессмысленно, а ложные сработки они дают охотно.
const MAX_LENGTH = 400;

export function classifyZhkhMessage(raw: string): Classification | null {
  if (!raw) return null;
  const text = raw.toLowerCase().replace(/ё/g, 'е');
  if (text.length > MAX_LENGTH) return null;

  // Отрицательные маркеры проверяем первыми: если человек спрашивает,
  // где купить кран, дальше считать нечего.
  const negatives = NEGATIVE.filter(n => text.includes(n.replace(/ё/g, 'е'))).length;
  if (negatives > 0) return null;

  // Вопрос без симптома — это вопрос. «Когда включат отопление?»
  // содержит тему, но не поломку; предлагать по нему заявку неуместно.
  const symptoms = SYMPTOMS.filter(s => text.includes(s)).length;
  if (symptoms === 0) return null;

  // Выбираем тему с наибольшим числом совпадений. Сообщение «в подъезде
  // течёт труба» задевает и leak, и common_property — берём то, где
  // попаданий больше, при равенстве побеждает первый по порядку
  // объявления (leak приоритетнее, он же и опаснее).
  let best: { category: ZhkhCategory; hits: number } | null = null;
  for (const [category, words] of Object.entries(TOPICS) as [ZhkhCategory, string[]][]) {
    const hits = words.filter(w => text.includes(w)).length;
    if (hits > 0 && (!best || hits > best.hits)) best = { category, hits };
  }
  if (!best) return null;

  // Уверенность. Формула намеренно грубая: точность здесь иллюзорна,
  // а порог всё равно подбирается по статистике из
  // telegram_suggestions.outcome. Важно лишь, чтобы больше совпадений
  // давало больше уверенности и чтобы шкала не выходила за единицу.
  const confidence = Math.min(1, 0.45 + best.hits * 0.15 + Math.min(symptoms, 3) * 0.1);

  return { category: best.category, confidence };
}

// Порог сработки. §14 требует «использовать порог уверенности».
// 0.7 означает: нужна либо пара попаданий по теме, либо тема плюс
// несколько симптомов. Лучше промолчать, чем раздражать чат ложным
// предложением — жители отключат бота после второго такого.
export const SUGGESTION_THRESHOLD = 0.7;

